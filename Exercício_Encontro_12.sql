USE DB_T05429_CARLOS_ALEXANDRE;

CREATE TABLE ACCOUNT (
	ID INT AUTO_INCREMENT PRIMARY KEY,
	STUDENT_NAME VARCHAR(100),
	BALANCE DECIMAL(10,2),
	CREATED_AT DATETIME
);

CREATE TABLE ACCOUNT_LOG (
	LOG_ID INT AUTO_INCREMENT PRIMARY KEY,
	ACCOUNT_ID INT,
	ACTION_TYPE VARCHAR(50),
	ACTION_DATE DATETIME
);

#1)PROCEDURE
DELIMITER //
CREATE PROCEDURE INSERT_ACCOUNT(
	IN P_STUDENT_NAME VARCHAR(100),
    IN P_BALANCE DECIMAL(10,2)
)
BEGIN
	INSERT INTO ACCOUNT (STUDENT_NAME, BALANCE, CREATED_AT)
	VALUES (P_STUDENT_NAME, P_BALANCE, NOW());
END //
DELIMITER ;

#2) TRIGGER

DELIMITER //
CREATE TRIGGER TRG_AFTER_INSERT_ACCOUNT
	AFTER INSERT ON ACCOUNT
    FOR EACH ROW
BEGIN
	INSERT INTO ACCOUNT_LOG (ACCOUNT_ID, ACTION_TYPE, ACTION_DATE)
    VALUES (NEW.ID, 'INSERT', UTC_TIMESTAMP());
END //
DELIMITER ;


CALL INSERT_ACCOUNT('ALUNO_1', 1000.00);
CALL INSERT_ACCOUNT('ALUNO_2', 1500.00);
CALL INSERT_ACCOUNT('ALUNO_3', 2000.00);
CALL INSERT_ACCOUNT("MARIA" , 3500.00);
CALL INSERT_ACCOUNT ("JULIA" , 2780.00);

