#PARTE_02 Crie as tabelas PLAYER, TEAM e MATCHES com colunas em inglês e maiúsculas, conforme definido em aula.

CREATE TABLE PLAYER (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR (100) NOT NULL,
    AGE INT,
    POSITION VARCHAR (50),
    SALARY DECIMAL (10,2),
    TEAM_ID INT
);

CREATE TABLE TEAM (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR (100)  NOT NULL,
    CITY VARCHAR (100),
    FOUNDATION_YEAR INT,
    STADIUM VARCHAR (100)
);

CREATE TABLE MATCHES (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    HOME_TEAM_ID INT,
    AWAY_TEAM_ID INT,
    MATCH_DATE DATE,
    HOME_SCORE INT,
    AWAY_SCORE INT,
    STADIUM VARCHAR (100)
);

