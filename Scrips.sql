CREATE TABLE NOVEL(
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(128) NOT NULL,
    YEAR YEAR,
    GENRE VARCHAR(64),
    AUDIENCE VARCHAR(32)
);

CREATE TABLE ACTOR(
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(64) NOT NULL,
    AGE INT,
	CHARACTER_NAME VARCHAR(64),
    SALARY INT
);

CREATE TABLE BROADCASTER(
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(64) NOT NULL,
    COUNTRY VARCHAR(32),
	FOUNDATION_YEAR CHAR (04)
);

