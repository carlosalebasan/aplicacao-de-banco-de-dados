CREATE TABLE BETTOR (-- JOGADOR
	ID INT NOT NULL AUTO_INCREMENT UNIQUE PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    DOCUMENT VARCHAR(20) UNIQUE, -- DOCUMENTO DE IDENTIFICAÇÃO
    CREATED_AT DATE DEFAULT (CURDATE()) -- DATA AUTOMÁTICA
);

CREATE TABLE BET (
	ID INT NOT NULL AUTO_INCREMENT UNIQUE PRIMARY KEY,
    AMOUNT NUMERIC NOT NULL, -- VALOR APOSTADO
    TYPE VARCHAR (1)NOT NULL
		CHECK (TYPE IN ('A', 'B', 'C')), -- MODALIDADE DA APOSTA
	DESCRIPTION VARCHAR(20) NOT NULL
		CHECK (CHAR_LENGTH(DESCRIPTION) BETWEEN 3 AND 20), -- DESCRIÇÃO QUE DETALHA O QUE FOI APOSTADO MIN 3 E MAX 20 CARACTERES
	CREATED_AT DATE DEFAULT (CURDATE()),
    BETTOR_ID INT
);

